#!/usr/bin/env node
/**
 * Scans public/invite-cards/leads/<id>/product-a|b|c.<ext> and writes
 * src/data/leadPilotProductManifest.ts so product image paths are extension-agnostic
 * in application code (registry uses resolveLeadProductPath only).
 *
 * Preference when multiple extensions exist: .webp, .jpg, .jpeg, .png
 *
 * Run: node scripts/sync-lead-product-manifest.mjs
 * (Also runs after npm run fetch:lead-pilot-assets and before vite build.)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const LEADS_DIR = path.join(ROOT, "public", "invite-cards", "leads");
const OUT_FILE = path.join(ROOT, "src", "data", "leadPilotProductManifest.ts");

const EXT_ORDER = [".webp", ".jpg", ".jpeg", ".png"];
const SLOTS = ["a", "b", "c"];

function pickProductUrl(leadDir, slot) {
  let entries = [];
  try {
    entries = fs.readdirSync(leadDir, { withFileTypes: true });
  } catch {
    return null;
  }
  const prefix = `product-${slot}.`;
  const candidates = [];
  for (const e of entries) {
    if (!e.isFile()) continue;
    const name = e.name;
    if (!name.toLowerCase().startsWith(prefix)) continue;
    const ext = path.extname(name).toLowerCase();
    const idx = EXT_ORDER.indexOf(ext);
    if (idx === -1) continue;
    candidates.push({ name, idx });
  }
  if (candidates.length === 0) return null;
  candidates.sort((x, y) => x.idx - y.idx);
  const leadId = path.basename(leadDir);
  return `/invite-cards/leads/${leadId}/${candidates[0].name}`;
}

function main() {
  let leadIds = [];
  try {
    leadIds = fs
      .readdirSync(LEADS_DIR, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
      .sort();
  } catch (e) {
    console.warn("sync-lead-product-manifest: no leads dir", e.message);
    leadIds = [];
  }

  const rows = {};
  for (const id of leadIds) {
    const dir = path.join(LEADS_DIR, id);
    const a = pickProductUrl(dir, "a");
    const b = pickProductUrl(dir, "b");
    const c = pickProductUrl(dir, "c");
    rows[id] = { a, b, c };
  }

  const lines = [
    `/** Generated by scripts/sync-lead-product-manifest.mjs — do not edit by hand. */`,
    ``,
    `export type LeadProductSlot = "a" | "b" | "c";`,
    ``,
    `export const LEAD_PRODUCT_URLS: Record<string, Partial<Record<LeadProductSlot, string>>> = {`,
  ];

  for (const id of leadIds) {
    const { a, b, c } = rows[id];
    const parts = [];
    if (a) parts.push(`a: ${JSON.stringify(a)}`);
    if (b) parts.push(`b: ${JSON.stringify(b)}`);
    if (c) parts.push(`c: ${JSON.stringify(c)}`);
    if (parts.length === 0) continue;
    lines.push(`  ${JSON.stringify(id)}: { ${parts.join(", ")} },`);
  }

  lines.push(`};`);
  lines.push(``);
  lines.push(
    `export function resolveLeadProductPath(leadId: string, slot: LeadProductSlot): string {`,
  );
  lines.push(`  const row = LEAD_PRODUCT_URLS[leadId];`);
  lines.push(`  const url = row?.[slot];`);
  lines.push(`  if (url) return url;`);
  lines.push(
    `  return \`/invite-cards/leads/\${leadId}/product-\${slot}.jpg\`;`,
  );
  lines.push(`}`);
  lines.push(``);

  fs.writeFileSync(OUT_FILE, lines.join("\n"), "utf8");
  console.log(`Wrote ${path.relative(ROOT, OUT_FILE)} (${leadIds.length} leads)`);
}

main();
